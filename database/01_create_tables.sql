
-- FinGuard: Database Schema
-- Step 1: Create the application users table

CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    account_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT pk_app_users PRIMARY KEY (user_id),
    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT chk_app_users_status
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED'))
);



-- Step 2: Create Financial Accounts Table

CREATE TABLE financial_accounts (
    account_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id NUMBER NOT NULL,
    account_name VARCHAR2(100) NOT NULL,
    account_type VARCHAR2(30) NOT NULL,
    balance NUMBER(15,2) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_financial_accounts
        PRIMARY KEY (account_id),

    CONSTRAINT fk_accounts_user
        FOREIGN KEY (user_id)
        REFERENCES app_users(user_id),

    CONSTRAINT chk_account_type
        CHECK (account_type IN ('SAVINGS', 'CURRENT', 'CASH')),

    CONSTRAINT chk_account_balance
        CHECK (balance >= 0)
);


-- Step 3: Create Transactions Table

CREATE TABLE transactions (
    transaction_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    account_id NUMBER NOT NULL,
    destination_account_id NUMBER,
    transaction_type VARCHAR2(20) NOT NULL,
    amount NUMBER(15,2) NOT NULL,
    category VARCHAR2(50) NOT NULL,
    description VARCHAR2(255),
    transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    transaction_status VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,

    CONSTRAINT pk_transactions
        PRIMARY KEY (transaction_id),

    CONSTRAINT fk_transactions_account
        FOREIGN KEY (account_id)
        REFERENCES financial_accounts(account_id),

    CONSTRAINT fk_transactions_destination
        FOREIGN KEY (destination_account_id)
        REFERENCES financial_accounts(account_id),

    CONSTRAINT chk_transaction_type
        CHECK (transaction_type IN ('INCOME', 'EXPENSE', 'TRANSFER')),

    CONSTRAINT chk_transaction_amount
        CHECK (amount > 0),

    CONSTRAINT chk_transaction_status
        CHECK (transaction_status IN ('PENDING', 'COMPLETED', 'FAILED')),

    CONSTRAINT chk_transfer_destination
        CHECK (
            (transaction_type = 'TRANSFER'
             AND destination_account_id IS NOT NULL
             AND destination_account_id <> account_id)
            OR
            (transaction_type IN ('INCOME', 'EXPENSE')
             AND destination_account_id IS NULL)
        )
);


-- Step 4: Create Budgets Table

CREATE TABLE budgets (
    budget_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id NUMBER NOT NULL,
    category VARCHAR2(50) NOT NULL,
    monthly_limit NUMBER(15,2) NOT NULL,
    budget_month DATE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_budgets
        PRIMARY KEY (budget_id),

    CONSTRAINT fk_budgets_user
        FOREIGN KEY (user_id)
        REFERENCES app_users(user_id),

    CONSTRAINT chk_budget_limit
        CHECK (monthly_limit > 0),

    CONSTRAINT chk_budget_month
        CHECK (budget_month = TRUNC(budget_month, 'MM')),

    CONSTRAINT uq_budget_user_category_month
        UNIQUE (user_id, category, budget_month)
);


-- Step 5: Create Savings Goals Table

CREATE TABLE savings_goals (
    goal_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id NUMBER NOT NULL,
    goal_name VARCHAR2(100) NOT NULL,
    target_amount NUMBER(15,2) NOT NULL,
    saved_amount NUMBER(15,2) DEFAULT 0 NOT NULL,
    target_date DATE,
    goal_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_savings_goals
        PRIMARY KEY (goal_id),

    CONSTRAINT fk_savings_user
        FOREIGN KEY (user_id)
        REFERENCES app_users(user_id),

    CONSTRAINT chk_savings_target
        CHECK (target_amount > 0),

    CONSTRAINT chk_savings_amount
        CHECK (saved_amount >= 0),

    CONSTRAINT chk_savings_status
        CHECK (goal_status IN ('ACTIVE', 'COMPLETED', 'CANCELLED'))
);


-- Step 6: Create Transaction Risk Alerts Table

CREATE TABLE transaction_risk_alerts (
    alert_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    transaction_id NUMBER NOT NULL,
    risk_level VARCHAR2(20) NOT NULL,
    risk_reason VARCHAR2(500) NOT NULL,
    alert_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    detected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,

    CONSTRAINT pk_risk_alerts
        PRIMARY KEY (alert_id),

    CONSTRAINT fk_risk_transaction
        FOREIGN KEY (transaction_id)
        REFERENCES transactions(transaction_id),

    CONSTRAINT chk_risk_level
        CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),

    CONSTRAINT chk_alert_status
        CHECK (alert_status IN ('OPEN', 'REVIEWED', 'DISMISSED'))
);


-- Step 7: Create Audit Logs Table

CREATE TABLE audit_logs (
    log_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id NUMBER,
    table_name VARCHAR2(100) NOT NULL,
    record_id NUMBER,
    action_type VARCHAR2(20) NOT NULL,
    old_value CLOB,
    new_value CLOB,
    action_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_audit_logs
        PRIMARY KEY (log_id),

    CONSTRAINT fk_audit_user
        FOREIGN KEY (user_id)
        REFERENCES app_users(user_id),

    CONSTRAINT chk_audit_action
        CHECK (action_type IN ('INSERT', 'UPDATE', 'DELETE'))
);
